// Embeds the library's AI-agent docs (llms.txt, llms-full.txt) into the server so `get_docs` works offline.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const read = (f) => readFileSync(join(root, f), 'utf8');
writeFileSync(
  join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'docs.generated.ts'),
  `// GENERATED by scripts/build-docs.mjs from the repo's llms.txt / llms-full.txt. Do not edit.\nexport const LLMS_TXT = ${JSON.stringify(read('llms.txt'))};\nexport const LLMS_FULL = ${JSON.stringify(read('llms-full.txt'))};\n`,
);
console.log('embedded llms.txt and llms-full.txt');
