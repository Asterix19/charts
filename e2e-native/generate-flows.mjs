#!/usr/bin/env -S npx tsx
// Generates e2e-native/flows/10-scenarios.yaml from the shared scenario catalogue, so the native suite
// covers exactly the scenarios the web suites do and can never drift from them.
//   node/tsx e2e-native/generate-flows.mjs          write the file
//   node/tsx e2e-native/generate-flows.mjs --check  exit 1 if the committed file is stale (used in CI)
import { readFileSync, writeFileSync } from 'node:fs';
import { DEFAULT_LAB_STATE, LAB_CAPABILITIES } from '@stacklatte/chart-engine/lab';
import { SCENARIOS } from '@stacklatte/chart-examples';

const arg = (name) => process.argv.find((a) => a.startsWith(`--${name}=`))?.split('=')[1];
const clean = process.argv.includes('--clean');
const exclude = new Set((arg('exclude') ?? '').split(',').filter(Boolean));
const out = new URL(arg('out') ?? './flows/10-scenarios.yaml', import.meta.url);

const steps = [];
const add = (...lines) => steps.push(...lines);

for (const s of SCENARIOS.filter((x) => !exclude.has(x.id) && !(clean && x.kind === 'live'))) {
  const n = s.data().length;
  add(`# ── ${s.id} (${s.kind}) ──`);
  add(`- openLink: demo://scenarios?id=${s.id}${clean ? '&clean=1' : ''}`);
  // iOS asks "Open in demo?" for custom-scheme links; confirm it when it appears.
  add(`- extendedWaitUntil:`, `    visible: "Open in.*"`, `    timeout: 4000`, `    optional: true`);
  add(`- tapOn:`, `    text: "Open"`, `    optional: true`);
  // The stats label reads "stats scenario=<id> candles=<n> ticks=<k>" for assistive tech and for Maestro.
  add(`- extendedWaitUntil:`, `    visible: ".*scenario=${s.id} candles=${s.live ? '[0-9]+' : n} .*"`, `    timeout: 30000`);
  add(`- assertVisible:`, `    id: title`);
  add(`- assertVisible: "${s.title.replace(/"/g, '\\"')}"`);

  if (!clean && n >= 20 && !s.live) {
    // pan left then right, like a user scrubbing through history
    add(`- swipe:`, `    start: 30%, 55%`, `    end: 80%, 55%`, `    duration: 400`);
    add(`- swipe:`, `    start: 80%, 55%`, `    end: 20%, 55%`, `    duration: 400`);
  }
  if (!clean && s.kind === 'stress') {
    // hammer it: repeated full-width drags
    for (let i = 0; i < 6; i++) add(`- swipe:`, `    start: ${i % 2 ? 85 : 15}%, 55%`, `    end: ${i % 2 ? 15 : 85}%, 55%`, `    duration: 250`);
  }
  if (s.live) {
    add(`- extendedWaitUntil:`, `    visible: ".*ticks=[1-9][0-9]*.*"`, `    timeout: ${Math.max(15000, s.live.tickMs * 10)}`);
    add(`- swipe:`, `    start: 30%, 55%`, `    end: 70%, 55%`, `    duration: 300`);
    add(`- assertVisible:`, `    id: stats`);
  }
  add(`- assertVisible:`, `    id: chart-host`);
  add(`- takeScreenshot: scenario-${s.id}`, '');
}

const header = `# GENERATED by e2e-native/generate-flows.mjs from @stacklatte/chart-examples — do not edit by hand.
appId: com.anonymous.demo
---
- runFlow: ../helpers/launch.yaml
`;
const yaml = header + `${steps.join('\n')}\n`;

// ── the Lab: every capability, set through a deep link, plus a few real taps on the visible controls ──
const lab = [];
const L = (...lines) => lab.push(...lines);
const open = (query) => L(`- openLink: demo://lab?${query}`, `- extendedWaitUntil:`, `    visible: "Open in.*"`, `    timeout: 4000`, `    optional: true`, `- tapOn:`, `    text: "Open"`, `    optional: true`);
const check = (name) => L(`- assertVisible:`, `    id: candle-count`, `- assertVisible:`, `    id: package-banner`, `- takeScreenshot: lab-${name}`, '');
const enc = (v) => encodeURIComponent(String(v));
L('# ── real taps on the controls visible without scrolling ──');
open('reset=1');
L(`- tapOn:`, `    id: tab-lab`);
L(`- assertVisible:`, `    id: package-banner`, `- assertVisible: "LIVE"   # HUD is on by default in the Lab`);
L(`- tapOn:`, `    id: lab-count-100`, `- assertVisible: "100 candles.*"`);
L(`- tapOn:`, `    id: lab-count-2000`, `- assertVisible: "2,000 candles.*"`);
L(`- tapOn:`, `    id: lab-count-500`, `- assertVisible: "500 candles.*"`);
L(`- tapOn:`, `    id: lab-live-100`, `- extendedWaitUntil:`, `    visible: "package-banner.*"`, `    timeout: 1000`, `    optional: true`, `- tapOn:`, `    id: lab-live-off`);
// The Volume-data switch is fully on screen in the first view, so it can be tapped for real. Controls further down
// (clipped behind the tab bar) are covered by the deep-link sweep below instead.
L(`- tapOn:`, `    id: lab-withVolume-switch`, `- assertVisible:`, `    id: candle-count`, `- tapOn:`, `    id: lab-withVolume-switch`);
check('taps');
L('# ── every control value, through the deep link, on top of a rich baseline ──');
const base = 'reset=1&preset=rich';
open(base); check('baseline');
for (const c of LAB_CAPABILITIES) {
  const k = c.control;
  const def = DEFAULT_LAB_STATE[c.id];
  if (c.id === 'reset') continue;
  if (k.kind === 'bool') {
    const rich = ['sma', 'ema', 'bb', 'vwap', 'rsi', 'macd', 'volume', 'markers', 'customPanel'].includes(c.id);
    const baseVal = rich ? true : def;
    open(`${base}&set=${c.id}=${!baseVal}`); check(`${c.id}-${!baseVal}`);
  } else if (k.kind === 'enum') {
    for (const o of k.options) {
      if (String(def) === o.value && !['count'].includes(c.id)) continue;
      open(`${base}&set=${c.id}=${enc(o.value)}`); check(`${c.id}-${o.value}`);
    }
  } else if (k.kind === 'number') {
    const needs = { smaPeriod: 'sma', emaPeriod: 'ema', bbPeriod: 'bb', bbMult: 'bb', rsiPeriod: 'rsi' }[c.id];
    void needs; // every dependent feature is on in the rich baseline
    open(`${base}&set=${c.id}=${k.max}`); check(`${c.id}-${k.max}`);
  } else if (k.kind === 'color') {
    open(`${base}&set=theme=custom;${c.id}=${enc('#22d3ee')}`); check(`${c.id}-cyan`);
  } else if (k.kind === 'action') {
    open(`${base}&act=${k.action}`); check(`act-${k.action}`);
  }
}
const labYaml = header + `${lab.join('\n')}\n`;

const targets = [
  [out, yaml, 'e2e-native/flows/10-scenarios.yaml'],
  ...(arg('out') ? [] : [[new URL('./flows/11-lab.yaml', import.meta.url), labYaml, 'e2e-native/flows/11-lab.yaml']]),
];

if (process.argv.includes('--check')) {
  let stale = false;
  for (const [url, content, label] of targets) {
    let current = '';
    try { current = readFileSync(url, 'utf8'); } catch { /* missing */ }
    if (current !== content) { console.error(`${label} is out of date. Run: npx tsx e2e-native/generate-flows.mjs`); stale = true; }
  }
  if (stale) process.exit(1);
  console.log('native scenario and Lab flows are in sync with the catalogue');
} else {
  for (const [url, content, label] of targets) writeFileSync(url, content);
  console.log(`wrote ${steps.filter((l) => l.startsWith('- openLink')).length} scenarios and ${lab.filter((l) => l.startsWith('- openLink')).length} Lab states`);
}
