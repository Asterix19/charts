#!/usr/bin/env -S npx tsx
// Generates e2e-native/flows/10-scenarios.yaml from the shared scenario catalogue, so the native suite
// covers exactly the scenarios the web suites do and can never drift from them.
//   node/tsx e2e-native/generate-flows.mjs          write the file
//   node/tsx e2e-native/generate-flows.mjs --check  exit 1 if the committed file is stale (used in CI)
import { readFileSync, writeFileSync } from 'node:fs';
import { SCENARIOS } from '@stacklatte/chart-examples';

const arg = (name) => process.argv.find((a) => a.startsWith(`--${name}=`))?.split('=')[1];
const clean = process.argv.includes('--clean');
const exclude = new Set((arg('exclude') ?? '').split(',').filter(Boolean));
const out = new URL(arg('out') ?? './flows/10-scenarios.yaml', import.meta.url);

const steps = [];
const add = (...lines) => steps.push(...lines);

for (const s of SCENARIOS.filter((x) => !exclude.has(x.id) && !(clean && x.kind === 'live'))) {
  const n = s.data().length;
  add(`# ── ${s.id} (${s.kind}) ──`);
  add(`- openLink: demo://scenarios?id=${s.id}${clean ? '&clean=1' : ''}`);
  // iOS asks "Open in demo?" for custom-scheme links; confirm it when it appears.
  add(`- extendedWaitUntil:`, `    visible: "Open in.*"`, `    timeout: 4000`, `    optional: true`);
  add(`- tapOn:`, `    text: "Open"`, `    optional: true`);
  // The stats label reads "stats scenario=<id> candles=<n> ticks=<k>" for assistive tech and for Maestro.
  add(`- extendedWaitUntil:`, `    visible: ".*scenario=${s.id} candles=${s.live ? '[0-9]+' : n} .*"`, `    timeout: 30000`);
  add(`- assertVisible:`, `    id: title`);
  add(`- assertVisible: "${s.title.replace(/"/g, '\\"')}"`);

  if (!clean && n >= 20 && !s.live) {
    // pan left then right, like a user scrubbing through history
    add(`- swipe:`, `    start: 30%, 55%`, `    end: 80%, 55%`, `    duration: 400`);
    add(`- swipe:`, `    start: 80%, 55%`, `    end: 20%, 55%`, `    duration: 400`);
  }
  if (!clean && s.kind === 'stress') {
    // hammer it: repeated full-width drags
    for (let i = 0; i < 6; i++) add(`- swipe:`, `    start: ${i % 2 ? 85 : 15}%, 55%`, `    end: ${i % 2 ? 15 : 85}%, 55%`, `    duration: 250`);
  }
  if (s.live) {
    add(`- extendedWaitUntil:`, `    visible: ".*ticks=[1-9][0-9]*.*"`, `    timeout: ${Math.max(15000, s.live.tickMs * 10)}`);
    add(`- swipe:`, `    start: 30%, 55%`, `    end: 70%, 55%`, `    duration: 300`);
    add(`- assertVisible:`, `    id: stats`);
  }
  add(`- assertVisible:`, `    id: chart-host`);
  add(`- takeScreenshot: scenario-${s.id}`, '');
}

const yaml = `# GENERATED by e2e-native/generate-flows.mjs from @stacklatte/chart-examples — do not edit by hand.
appId: com.anonymous.demo
---
- runFlow: ../helpers/launch.yaml
${steps.join('\n')}
`;

if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(out, 'utf8'); } catch { /* missing */ }
  if (current !== yaml) {
    console.error('e2e-native/flows/10-scenarios.yaml is out of date. Run: npx tsx e2e-native/generate-flows.mjs');
    process.exit(1);
  }
  console.log('native scenario flow is in sync with the catalogue');
} else {
  writeFileSync(out, yaml);
  console.log(`wrote ${steps.filter((l) => l.startsWith("- openLink")).length} scenarios to ${out.pathname.split("e2e-native/")[1]}`);
}
