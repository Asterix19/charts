#!/usr/bin/env node
// Generates llms-full.txt: llms.txt + every guide + the generated API reference, in one file an agent can
// ingest in a single fetch. Run after scripts/generate-api-docs.mjs.
//   node scripts/generate-llms-full.mjs           write llms-full.txt
//   node scripts/generate-llms-full.mjs --check   exit 1 if the committed file is stale
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(new URL('..', import.meta.url).pathname);
const read = (p) => readFileSync(resolve(root, p), 'utf8').trim();

const GUIDES = [
  'docs/why-use-this.md', 'docs/choosing-a-package.md', 'docs/react.md', 'docs/react-native.md', 'docs/angular.md',
  'docs/node-engine.md', 'docs/chartconfig-llm.md', 'docs/live-data.md', 'docs/performance.md', 'docs/testing.md',
  'docs/migrating-from-chart-core.md', 'docs/troubleshooting.md', 'docs/api-reference.md',
];

const sections = [
  '<!-- GENERATED by scripts/generate-llms-full.mjs from llms.txt, docs/*.md and docs/api-reference.md — do not edit by hand. -->',
  read('llms.txt'),
  ...GUIDES.map((g) => `\n\n---\n\n<!-- ${g} -->\n\n${read(g)}`),
];
// Relative links make no sense inside a single file; point them at the repository.
const body = sections.join('\n').replace(/^!\[[^\n]*\]\([^)\n]*\)[^\n]*\n?/gm, '').replace(/<!-- screenshots -->[\s\S]*?<!-- \/screenshots -->\n?/g, '').replace(/\]\(\.{1,2}\/([^)]+)\)/g, (_m, p) => `](https://github.com/Asterix19/charts/blob/main/${p.replace(/^docs\//, 'docs/')})`) + '\n';

const target = resolve(root, 'llms-full.txt');
if (process.argv.includes('--check')) {
  const cur = existsSync(target) ? readFileSync(target, 'utf8') : '';
  if (cur !== body) { console.error('llms-full.txt is out of date. Run: node scripts/generate-llms-full.mjs'); process.exit(1); }
  console.log('llms-full.txt is in sync');
} else {
  writeFileSync(target, body);
  console.log(`wrote llms-full.txt (${(body.length / 1024).toFixed(0)} kB, ~${Math.round(body.length / 4).toLocaleString()} tokens)`);
}
