#!/usr/bin/env node
// Generates docs/api-reference.md from the packages' real .d.ts files, so documented signatures can never
// drift from the shipped types. Run after `npm run build`.
//   node scripts/generate-api-docs.mjs           write docs/api-reference.md
//   node scripts/generate-api-docs.mjs --check   exit 1 if the committed file is stale
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(new URL('..', import.meta.url).pathname);
const require = createRequire(resolve(root, 'compat/package.json')); // TypeScript 6 classic API
const ts = require('typescript');

const PACKAGES = [
  ['@stacklatte/chart-engine', 'chart-engine/dist/index.d.ts', 'Platform-agnostic logic: indicators, viewport math, geometry, themes and the ChartConfig pipeline. Zero dependencies.'],
  ['@stacklatte/chart-canvas', 'chart-canvas/dist/index.d.ts', 'Framework-agnostic Canvas 2D renderer: `ChartController` plus the drawing primitives.'],
  ['@stacklatte/chart-web', 'chart-web/dist/index.d.ts', 'React renderer (Canvas 2D). Exports `SLChart` plus the whole engine.'],
  ['@stacklatte/chart-native', 'chart-native/dist/index.d.ts', 'React Native renderer (Skia). Exports `SLChart`, the layer components and the whole engine.'],
  ['@stacklatte/chart-angular', 'chart-angular/dist/types/stacklatte-chart-angular.d.ts', 'Angular standalone component `<sl-chart>`. Re-exports the whole engine.'],
];

function program(entry) {
  return ts.createProgram([resolve(root, entry)], {
    moduleResolution: ts.ModuleResolutionKind.Bundler, module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022,
    skipLibCheck: true, noEmit: true, jsx: ts.JsxEmit.ReactJSX, types: [],
  });
}

const oneLine = (s) => s.replace(/\s+/g, ' ').replace(/import\("[^"]+"\)\./g, '').trim();
const escapeCell = (s) => oneLine(s).replace(/\|/g, '\\|');
const doc = (checker, sym) => ts.displayPartsToString(sym.getDocumentationComment(checker)).trim();

function describeSymbol(checker, sym) {
  const target = sym.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(sym) : sym;
  const decl = target.declarations?.[0];
  if (!decl) return null;
  const name = sym.name;
  const text = doc(checker, target);
  const summary = text.split('\n\n')[0].replace(/\n/g, ' ');

  if (ts.isFunctionDeclaration(decl) || (ts.isVariableDeclaration(decl) && checker.getTypeOfSymbol(target).getCallSignatures().length)) {
    const sigs = checker.getTypeOfSymbol(target).getCallSignatures().map((s) => `${name}${checker.signatureToString(s, decl, ts.TypeFormatFlags.NoTruncation).replace(/^\(/, '(')}`);
    return { kind: 'function', name, sigs, summary };
  }
  if (ts.isInterfaceDeclaration(decl)) {
    const members = checker.getPropertiesOfType(checker.getDeclaredTypeOfSymbol(target)).map((p) => {
      const d = p.declarations?.[0];
      const optional = !!(p.flags & ts.SymbolFlags.Optional);
      let type = oneLine(checker.typeToString(checker.getTypeOfSymbol(p), d, ts.TypeFormatFlags.NoTruncation));
      if (optional) type = type.replace(/ \| undefined$/, '').replace(/^\((.*)\)$/, '$1');
      return { name: p.name, optional, type, doc: doc(checker, p) };
    });
    return { kind: 'interface', name, members, summary };
  }
  if (ts.isTypeAliasDeclaration(decl)) return { kind: 'type', name, text: oneLine(decl.getText()).slice(0, 700), summary };
  if (ts.isClassDeclaration(decl)) {
    const t = checker.getDeclaredTypeOfSymbol(target);
    const isPublic = (p) => !(p.declarations ?? []).some((d) => ts.getCombinedModifierFlags(d) & (ts.ModifierFlags.Private | ts.ModifierFlags.Protected));
    const members = checker.getPropertiesOfType(t).filter((p) => !p.name.startsWith('ɵ') && !p.name.startsWith('_') && isPublic(p)).map((p) => {
      const d = p.declarations?.[0];
      const pt = checker.getTypeOfSymbol(p);
      const sig = pt.getCallSignatures()[0];
      return { name: p.name, type: sig ? `${p.name}${checker.signatureToString(sig, d)}` : checker.typeToString(pt, d, ts.TypeFormatFlags.NoTruncation), method: !!sig, doc: doc(checker, p) };
    });
    return { kind: 'class', name, members, summary };
  }
  if (ts.isVariableDeclaration(decl)) {
    const t = checker.typeToString(checker.getTypeOfSymbol(target), decl, ts.TypeFormatFlags.NoTruncation);
    return { kind: 'const', name, type: oneLine(t).slice(0, 400), summary };
  }
  return { kind: 'other', name, summary };
}

function render() {
  const engineNames = new Set();
  const out = [
    '# API reference',
    '',
    '<!-- GENERATED by scripts/generate-api-docs.mjs from the packages\' .d.ts files — do not edit by hand. -->',
    '',
    'Every signature below is extracted from the types the packages actually ship. Renderer packages re-export the whole engine, so engine functions can be imported from any of them.',
    '',
  ];

  for (const [pkg, entry, blurb] of PACKAGES) {
    const p = program(entry);
    const checker = p.getTypeChecker();
    const sf = p.getSourceFile(resolve(root, entry));
    const mod = checker.getSymbolAtLocation(sf);
    let syms = checker.getExportsOfModule(mod).sort((a, b) => a.name.localeCompare(b.name));
    const isEngine = pkg === '@stacklatte/chart-engine';
    if (isEngine) syms.forEach((s) => engineNames.add(s.name));
    else syms = syms.filter((s) => !engineNames.has(s.name)); // renderers: only what they add

    out.push(`## ${pkg}`, '', blurb, '');
    if (!isEngine) out.push(`Also re-exports everything from \`@stacklatte/chart-engine\` (see above).`, '');

    const items = syms.map((s) => describeSymbol(checker, s)).filter(Boolean);
    const fns = items.filter((i) => i.kind === 'function');
    const ifaces = items.filter((i) => i.kind === 'interface');
    const classes = items.filter((i) => i.kind === 'class');
    const consts = items.filter((i) => i.kind === 'const');
    const types = items.filter((i) => i.kind === 'type');

    if (classes.length) {
      out.push('### Classes / components', '');
      for (const c of classes) {
        out.push(`#### \`${c.name}\``, '', c.summary, '', '| member | type | description |', '|---|---|---|');
        for (const m of c.members) out.push(`| \`${m.name}\` | \`${escapeCell(m.type)}\` | ${escapeCell(m.doc)} |`);
        out.push('');
      }
    }
    if (fns.length) {
      out.push('### Functions', '');
      for (const f of fns) {
        for (const sig of f.sigs) out.push('```ts', sig, '```');
        if (f.summary) out.push(f.summary);
        out.push('');
      }
    }
    if (ifaces.length) {
      out.push('### Interfaces', '');
      for (const i of ifaces) {
        out.push(`#### \`${i.name}\``, '');
        if (i.summary) out.push(i.summary, '');
        out.push('| property | type | required | description |', '|---|---|---|---|');
        for (const m of i.members) out.push(`| \`${m.name}\` | \`${escapeCell(m.type)}\` | ${m.optional ? 'no' : 'yes'} | ${escapeCell(m.doc)} |`);
        out.push('');
      }
    }
    if (types.length) {
      out.push('### Types', '');
      for (const t of types) out.push(`- \`${t.text}\`${t.summary ? ` — ${t.summary}` : ''}`);
      out.push('');
    }
    if (consts.length) {
      out.push('### Constants', '');
      for (const c of consts) out.push(`- \`${c.name}\`: \`${escapeCell(c.type)}\`${c.summary ? ` — ${c.summary}` : ''}`);
      out.push('');
    }
  }
  return out.join('\n').replace(/\n{3,}/g, '\n\n') + '\n';
}

const target = resolve(root, 'docs/api-reference.md');
const next = render();
if (process.argv.includes('--check')) {
  const cur = existsSync(target) ? readFileSync(target, 'utf8') : '';
  if (cur !== next) { console.error('docs/api-reference.md is out of date. Run: node scripts/generate-api-docs.mjs (after npm run build)'); process.exit(1); }
  console.log('docs/api-reference.md is in sync with the shipped types');
} else {
  writeFileSync(target, next);
  console.log(`wrote docs/api-reference.md (${next.split('\n').length} lines)`);
}
